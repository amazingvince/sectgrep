#!/usr/bin/env python3
"""Milestone C2 evidence (GOAL.md G-H): the seven C.5 validators on the fixture corpus and on the
converted eCFR corpus, and `sect-convert align` on two point-in-time dates of one title from the
versioner API. Writes eval/results/c2.md.

    python eval/eval_c2.py [--title 4 --old 2024-06-17 --new 2024-07-18]

Needs the converter built and a release sect binary. Dates not yet under raw/ are fetched.
"""
from __future__ import annotations

import argparse
import json
import platform
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CLI = ROOT / "packages" / "sect-convert" / "dist" / "cli.js"
SECT = next((p for p in [ROOT / "target" / "release" / "sect.exe", ROOT / "target" / "release" / "sect"] if p.exists()), Path("sect"))
OUT = ROOT / "eval" / "results" / "c2.md"


def run(cmd: list[str]) -> tuple[int, str, float]:
    t0 = time.perf_counter()
    r = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True, encoding="utf-8", errors="replace")
    return r.returncode, r.stdout + r.stderr, time.perf_counter() - t0


def validate(staging: str, raw_root: str, work: str) -> dict:
    code, out, secs = run(["node", str(CLI), "validate", staging, "--raw-root", raw_root, "--work", work, "--sect", str(SECT), "--json"])
    start = out.find("{")
    j = json.loads(out[start:]) if start >= 0 else {"issues": [], "validators": [], "errors": -1, "warnings": -1, "documents": 0}
    return {"exit": code, "seconds": secs, **j}


def align(title: int, old: str, new: str) -> dict:
    out_file = ROOT / "eval" / "results" / f"c2-align-title{title}.json"
    code, out, secs = run(["node", str(CLI), "align", f"cfr-title-{title}", old, new, "--out", str(out_file)])
    if code != 0:
        sys.exit(out)
    j = json.loads(out_file.read_text(encoding="utf-8"))
    return {"seconds": secs, "file": str(out_file.relative_to(ROOT)).replace("\\", "/"), **j}


def table_validators(v: dict) -> list[str]:
    md = ["| # | Validator | Documents | Errors | Warnings |", "|---|---|---|---|---|"]
    for s in v["validators"]:
        md.append(f"| {s['n']} | {s['name']} | {s['checked'] if not s.get('skipped') else 'skipped: ' + s['skipped']} | {s['errors']} | {s['warnings']} |")
    return md


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--title", type=int, default=4)
    ap.add_argument("--old", default="2024-06-17")
    ap.add_argument("--new", default="2024-07-18")
    a = ap.parse_args()
    fx = validate("fixtures/corpus", "fixtures", "fixtures/work")
    ec = validate("corpora/ecfr", ".", "work")
    al = align(a.title, a.old, a.new)
    node = run(["node", "--version"])[1].strip()
    md = ["# Milestone C2: C.5 validators and C.6 align\n"]
    md.append(f"Generated by `python eval/eval_c2.py` on {platform.system()} {platform.release()}, node {node}, `{SECT.name}` {run([str(SECT), '--version'])[1].strip()}.\n")
    md.append("## Validators on the fixture corpus (CI runs this)\n")
    md.append(f"`sect-convert validate fixtures/corpus --raw-root fixtures --work fixtures/work`: exit {fx['exit']}, {fx['documents']} documents, {fx['errors']} errors, {fx['warnings']} warnings, {fx['seconds']:.1f} s.\n")
    md.extend(table_validators(fx))
    md.append("")
    for i in fx["issues"]:
        md.append(f"- {i['level']} [{i['validator']}] {i['path']}: {i['message']}")
    md.append("")
    md.append("The fixture's raw sources (two Title 99 snapshots, the notice XML, the ordinance PDF and its elements) are generated by `packages/sect-convert/scripts/make-fixture-raw.mjs`; the note has no raw and is checked through its `sources` list.\n")
    md.append("## Validators on the converted eCFR corpus (three titles, six notices)\n")
    md.append(f"`sect-convert validate corpora/ecfr --raw-root . --work work`: exit {ec['exit']}, {ec['documents']} documents, {ec['errors']} errors, {ec['warnings']} warnings, {ec['seconds']:.1f} s.\n")
    md.extend(table_validators(ec))
    md.append("")
    kinds: dict[str, int] = {}
    for i in ec["issues"]:
        key = f"{i['level']} [{i['validator']}] " + " ".join(w for w in i["message"].split() if not any(c.isdigit() for c in w) and ":" not in w)[:90]
        kinds[key] = kinds.get(key, 0) + 1
    md.append("| Count | Issue (numbers and ids elided) |")
    md.append("|---|---|")
    for k, c in sorted(kinds.items(), key=lambda kv: -kv[1])[:15]:
        md.append(f"| {c} | {k} |")
    md.append("")
    md.append(f"## Align: Title {a.title}, {a.old} -> {a.new} (versioner point-in-time XML)\n")
    s = al["summary"]
    md.append(f"`sect-convert align cfr-title-{a.title} {a.old} {a.new}`: {al['old']['sections']} sections effective {al['old']['effective']} -> {al['new']['sections']} sections effective {al['new']['effective']}; {s['unchanged']} unchanged, {s['changed']} changed, {s['renumbered']} renumbered, {s['moved']} moved, {s['added']} added, {s['removed']} removed; {al['seconds']:.1f} s including the converter runs; full output in `{al['file']}`.\n")
    md.append("| Kind | Id | Level | Title | Similarity | First line added |")
    md.append("|---|---|---|---|---|---|")
    for c in al["changes"][:25]:
        first = (c.get("diff") or {}).get("added", [""])
        md.append(f"| {c['kind']} | {c.get('old_id', c['id'])}{' -> ' + c['new_id'] if c.get('new_id') else ''} | {c['level']} | {c['title'][:50]} | {c.get('similarity', '')} | {(first[0] if first else '')[:80].replace('|', '/')} |")
    md.append("")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(md) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}: fixture exit {fx['exit']} ({fx['errors']} errors), ecfr exit {ec['exit']} ({ec['errors']} errors, {ec['warnings']} warnings, {ec['seconds']:.0f} s), align {s}")


if __name__ == "__main__":
    main()
