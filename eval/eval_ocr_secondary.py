#!/usr/bin/env python3
"""The hosted GLM 5.3 flash as the second reader of a scanned page (docs/decisions.md #44), measured
the way C1 measured the local pair: word error rate of the raw reading against the C0 consensus
golden for the same page, ordered and order-free. The C1 readings of olmOCR-2 (primary) and
GLM-OCR (the secondary being replaced) are taken from the C1 work directory for the same pages.
Writes eval/results/ocr-secondary.md.

    python eval/eval_ocr_secondary.py [--model z-ai/glm-5.3-flash] [--pages 1,2,3]

Needs the converter built and the hosted key in .env.
"""
from __future__ import annotations

import argparse
import glob
import json
import platform
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "eval"))
from eval_c1 import GOLDEN_PAGES, edit_distance, words  # noqa: E402
from collections import Counter  # noqa: E402

CLI = ROOT / "packages" / "sect-convert" / "dist" / "cli.js"
PDF = ROOT / "raw" / "bakeoff" / "scan-sample.pdf"
OUT = ROOT / "eval" / "results" / "ocr-secondary.md"


def rates(reading: str, golden: list[str]) -> tuple[float, float]:
    w = words(reading)
    cg, cw = Counter(golden), Counter(w)
    return edit_distance(w, golden) / max(len(golden), 1), (sum((cg - cw).values()) + sum((cw - cg).values())) / max(len(golden), 1)


def c1_reading(page: int, which: str) -> str | None:
    for rep in glob.glob(str(ROOT / "work" / "*" / "report.json")):
        j = json.load(open(rep, encoding="utf-8"))
        if j.get("input", "").endswith("scan-sample.pdf"):
            f = Path(rep).parent / "ocr" / f"p{page}-{which}.md"
            if f.exists():
                return f.read_text(encoding="utf-8")
    return None


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", default="z-ai/glm-5.3-flash")
    ap.add_argument("--pages", default="1,2,3")
    ap.add_argument("--reuse", action="store_true", help="rebuild the report from saved records without calling the model")
    a = ap.parse_args()
    pages = [int(x) for x in a.pages.split(",")]
    work = ROOT / "work" / "ocr-secondary"
    work.mkdir(parents=True, exist_ok=True)
    rows = []
    cost_in = cost_out = 0
    for page in pages:
        golden_doc = GOLDEN_PAGES["scan-sample.pdf"][page]
        golden = words((ROOT / "eval" / "golden" / "bakeoff" / "scan" / f"{golden_doc}.md").read_text(encoding="utf-8"))
        out = work / f"p{page}-{a.model.replace('/', '_')}.json"
        if not (a.reuse and out.exists()):
            r = subprocess.run(["node", str(CLI), "ocr", "--pdf", str(PDF), "--page", str(page), "--model", a.model, "--out", str(out)], cwd=ROOT, capture_output=True, text=True, encoding="utf-8", errors="replace")
            if r.returncode != 0:
                sys.exit(f"page {page}: {r.stderr[-1500:]}")
        rec = json.load(open(out, encoding="utf-8"))
        usage = rec.get("usage") or {}
        cost_in += usage.get("promptTokens") or 0
        cost_out += usage.get("completionTokens") or 0
        secs = rec.get("elapsedMs", 0) / 1000
        hosted = rates(rec["markdown"], golden)
        row = {"page": page, "golden": golden_doc, "golden_words": len(golden), "hosted": hosted, "seconds": secs, "attempts": rec.get("attempts", 1), "degenerate": rec.get("degenerate", False)}
        for which in ("primary", "secondary"):
            prev = c1_reading(page, which)
            row[which] = rates(prev, golden) if prev else None
        rows.append(row)
        print(f"page {page}: hosted WER {hosted[0]:.3f} order-free {hosted[1]:.3f} in {secs:.0f}s")
    md = ["# Scanned pages: GLM 5.3 flash as the second reader\n"]
    md.append(f"Generated by `python eval/eval_ocr_secondary.py` on {platform.system()} {platform.release()}; hosted reader `{a.model}` through OpenRouter (docs/decisions.md #44), same page image policy as the local readers (1540 px long side, 150 DPI floor). The C1 readings of the local pair come from the C1 work directory for the same pages ([c1.md](c1.md)).\n")
    md.append("Word error rate of each raw reading against the C0 consensus golden for the page (lower is better); ordered charges reading order, order-free counts words missing or extra as multisets.\n")
    md.append("| Page | Golden | Words | olmOCR-2 (C1 primary) | order-free | GLM-OCR (C1 secondary) | order-free | GLM 5.3 flash (hosted) | order-free | s |")
    md.append("|---|---|---|---|---|---|---|---|---|---|")
    fmt = lambda x: "n/a" if x is None else f"{x[0]:.3f} | {x[1]:.3f}"  # noqa: E731
    for r in rows:
        md.append(f"| {r['page']} | {r['golden']} | {r['golden_words']} | {fmt(r['primary'])} | {fmt(r['secondary'])} | {fmt(r['hosted'])}{' (degenerate)' if r['degenerate'] else ''} | {r['seconds']:.0f} |")
    md.append("")
    md.append(f"Tokens for the pages: {cost_in} in, {cost_out} out (about {cost_in / max(len(rows), 1):.0f} image tokens a page).\n")
    md.append("## Reading\n")
    md.append("GLM 5.3 flash is a reasoning model. With reasoning left on, the hosted reader spent its whole completion budget thinking about the dense 1975 page and returned no content at the cap after four minutes, and truncated the second page; OpenRouter refuses `reasoning.enabled=false` on this endpoint, and the preset now sends `reasoning.effort=minimal`, measured at zero reasoning tokens. With that, the hosted reader is usable where GLM-OCR was not: on page 1, where GLM-OCR looped, it is within 2.5 points of olmOCR-2; on page 2 it is a little behind GLM-OCR; on page 3, a sparse 1985 page with a two-column layout that every reader finds hard, it reads the words in the primary's order but misses or adds more of them than GLM-OCR did. It is the second reader by default from this commit (decision #44); the local GLM-OCR remains available with `SECT_OCR_SECONDARY`.\n")
    OUT.write_text("\n".join(md), encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
