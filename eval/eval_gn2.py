#!/usr/bin/env python3
"""Pre-H3 groundwork (GOAL.md G-N2): Title 4 re-converted with per-section effective dates from
the versioner, and re-ingested through the harness with explicit citations linked in code,
trimmed search results and a compact prompt. Writes eval/results/gn2.md and appends the ingest
re-run to eval/results/h1.md (through eval/eval_h1.py --append).

    python eval/eval_gn2.py [--title 4] [--staging staging-gn2] [--concurrency 12] [--no-ingest]

Needs the converter and harness built, a release sect binary, and the model provider from .env.
"""
from __future__ import annotations

import argparse
import glob
import json
import platform
import re
import subprocess
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONVERT = ROOT / "packages" / "sect-convert" / "dist" / "cli.js"
OUT = ROOT / "eval" / "results" / "gn2.md"


def run(cmd: list[str]) -> subprocess.CompletedProcess[str]:
    r = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True, encoding="utf-8", errors="replace")
    if r.returncode != 0:
        sys.exit(f"{' '.join(str(c) for c in cmd)}\n{r.stdout[-3000:]}\n{r.stderr[-3000:]}")
    return r


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--title", type=int, default=4)
    ap.add_argument("--staging", default="staging-gn2")
    ap.add_argument("--concurrency", type=int, default=12)
    ap.add_argument("--no-ingest", action="store_true")
    ap.add_argument("--notes", default="", help="what the numbers do not show")
    a = ap.parse_args()
    xml = sorted(glob.glob(str(ROOT / "raw" / f"cfr-title-{a.title}" / "*" / f"ECFR-title{a.title}.xml")))[-1]
    rel = str(Path(xml).relative_to(ROOT)).replace("\\", "/")
    # (2) Re-convert with the versioner's dates into the converter output and the ingest input.
    lines = []
    for out in ("corpora/ecfr", "work/ingest-input"):
        r = run(["node", str(CONVERT), "ecfr", "--xml", rel, "--title", str(a.title), "--out", out])
        lines = [l for l in r.stdout.splitlines() if l.strip()]
    dates_line = next((l for l in lines if l.startswith("section dates")), "")
    spread = Counter()
    for f in (ROOT / "work" / "ingest-input" / f"cfr-title-{a.title}").rglob("*.md"):
        head = f.read_text(encoding="utf-8")[:1500]
        if re.search(r"^level:\s*\"?section", head, re.M):
            m = re.search(r"^effective:\s*(\d{4})-\d{2}-\d{2}", head, re.M)
            if m:
                spread[m.group(1)] += 1
    versions = Path(xml).parent / "versions.json"
    title_date = None
    if (Path(xml).parent / "versioner.json").exists():
        title_date = json.load(open(Path(xml).parent / "versioner.json", encoding="utf-8")).get("up_to_date_as_of")
    # (1) The ingest re-run, appended to h1.md.
    h1 = ""
    if not a.no_ingest:
        r = run([sys.executable, str(ROOT / "eval" / "eval_h1.py"), "--title", str(a.title), "--staging", a.staging, "--concurrency", str(a.concurrency), "--append", "Re-run after G-N2: citations linked in code, trimmed results, compact prompt"])
        h1 = r.stdout.strip().splitlines()[-1]
    md = ["# Pre-H3 groundwork (G-N2)\n"]
    md.append(f"Generated by `python eval/eval_gn2.py --title {a.title}` on {platform.system()} {platform.release()}.\n")
    md.append("## Per-section effective dates\n")
    md.append(f"`sect-convert ecfr` now dates each section's Expression from the versioner's `versions` endpoint (cached as `{versions.relative_to(ROOT).as_posix() if versions.exists() else 'raw/cfr-title-N/<date>/versions.json'}`), bounded by the title's up-to-date-as-of date {title_date or '(unknown)'}; a section without a date keeps the title date. Converter line: `{dates_line}`\n")
    md.append("| Year the current text took effect | Sections |")
    md.append("|---|---|")
    for y, n in sorted(spread.items()):
        md.append(f"| {y} | {n} |")
    md.append("")
    md.append("## Ingest cost after the groundwork\n")
    summary = re.sub(r"^wrote \S+: ", "", h1) if h1 else "ingest re-run skipped (--no-ingest)"
    md.append(f"{summary}.\n")
    # Before and after, from the two runs' usage files (the H1 run in staging/, this one in the given staging).
    runs = []
    for label, st in (("H1 (2026-09-04, before)", "staging"), ("after G-N2", a.staging)):
        u = next(iter(glob.glob(str(ROOT / st / f"cfr-title-{a.title}-*" / "usage.json"))), None)
        sub = next(iter(glob.glob(str(ROOT / st / f"cfr-title-{a.title}-*" / "submit.json"))), None)
        if u:
            uj = json.load(open(u, encoding="utf-8"))
            sj = json.load(open(sub, encoding="utf-8")) if sub else {}
            sections = sum(1 for f in (Path(u).parent / ".ingest").glob("*.json") if not any(fl.startswith("structural") for fl in json.load(open(f, encoding="utf-8"))["flags"]))
            runs.append((label, uj, sj, sections))
    if runs:
        md.append("| Run | Sections with a model turn | Model calls | Calls per section | Prompt tokens | Prompt tokens per call | Completion tokens | Cost $ | Document tokens | $ per 1M document tokens | References linked | Of them in code |")
        md.append("|---|---|---|---|---|---|---|---|---|---|---|---|")
        for label, uj, sj, sections in runs:
            dt = uj.get("document_tokens") or 1
            md.append(f"| {label} | {sections} | {uj['calls']} | {uj['calls'] / max(sections, 1):.1f} | {uj['input']} | {uj['input'] // max(uj['calls'], 1)} | {uj['output']} | {uj['cost']:.4f} | {uj['document_tokens']} | {1e6 * uj['cost'] / dt:.2f} | {sj.get('xrefs_resolved', '')} | {uj.get('deterministic', 0)} |")
        md.append("")
    md.append("The full run table is the last section of [h1.md](h1.md): explicit citations with one real target are linked by the harness before any model call and recorded in `provenance.deterministic_xrefs`; search results reach the agent trimmed to the hit headers and the matching lines with one line of context; the agent carries four tools with one-sentence descriptions and a skill of about a thousand tokens.\n")
    md.append("## Resolve\n")
    md.append("`sect-harness resolve --run <run_id> --id <section id> --pick ingest|verifier|none|<id>` applies a person's decision to staging, re-runs the evidence checks and consensus for the section, merges it and whatever it unblocked through the merge script, and appends the decision to the examples in `docs/SKILL-ingest.md`; covered by `packages/sect-harness/test/gn2.test.ts`.\n")
    if a.notes:
        md.append("## Notes\n")
        md.append(a.notes + "\n")
    OUT.write_text("\n".join(md), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}; spread {dict(sorted(spread.items()))}; {h1}")


if __name__ == "__main__":
    main()
