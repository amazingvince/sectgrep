#!/usr/bin/env python3
"""Milestone H1 evidence (GOAL.md G-L): one ingest run over a converted eCFR title, its validator
pass rate, and the model cost per document token. Writes eval/results/h1.md.

    python eval/eval_h1.py [--title 4] [--limit N] [--dry-run] [--staging staging]

Needs the converter and harness built, a release sect binary, and (unless --dry-run) the model
provider from .env. The run is idempotent: a second call over the same title reads the ledger.
"""
from __future__ import annotations

import argparse
import glob
import json
import platform
import subprocess
import sys
import time
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONVERT = ROOT / "packages" / "sect-convert" / "dist" / "cli.js"
HARNESS = ROOT / "packages" / "sect-harness" / "dist" / "cli.js"
SECT = next((p for p in [ROOT / "target" / "release" / "sect.exe", ROOT / "target" / "release" / "sect"] if p.exists()), Path("sect"))
OUT = ROOT / "eval" / "results" / "h1.md"


def run(cmd: list[str], check: bool = True) -> subprocess.CompletedProcess[str]:
    r = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True, encoding="utf-8", errors="replace")
    if check and r.returncode != 0:
        sys.exit(f"{' '.join(str(c) for c in cmd)}\n{r.stdout[-3000:]}\n{r.stderr[-3000:]}")
    return r


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--title", type=int, default=4)
    ap.add_argument("--limit", type=int)
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--staging", default="staging")
    ap.add_argument("--concurrency", type=int, default=4)
    a = ap.parse_args()
    xml = sorted(glob.glob(str(ROOT / "raw" / f"cfr-title-{a.title}" / "*" / f"ECFR-title{a.title}.xml")))[-1]
    inp = ROOT / "work" / "ingest-input"
    run(["node", str(CONVERT), "ecfr", "--xml", str(Path(xml).relative_to(ROOT)).replace("\\", "/"), "--title", str(a.title), "--out", str(inp)])
    source = f"cfr-title-{a.title}"
    cmd = ["node", str(HARNESS), "ingest", "--input", str(inp / source), "--source", source, "--corpus", "corpora/ecfr", "--staging", a.staging, "--sect", str(SECT), "--concurrency", str(a.concurrency), "--json"]
    if a.limit:
        cmd += ["--limit", str(a.limit)]
    if a.dry_run:
        cmd.append("--dry-run")
    t0 = time.perf_counter()
    r = run(cmd, check=False)
    secs = time.perf_counter() - t0
    start = r.stdout.find("{")
    if start < 0:
        sys.exit(f"no result from the harness:\n{r.stdout[-2000:]}\n{r.stderr[-2000:]}")
    res = json.loads(r.stdout[start:])
    run_dir = Path(res["runDir"])
    usage = res["usage"]
    summary = res.get("summary")
    # Validator pass rate: documents in the staging with no error, over the seven validators.
    v = run(["node", str(CONVERT), "validate", str(run_dir), "--corpus", "corpora/ecfr", "--raw-root", ".", "--work", "work", "--sect", str(SECT), "--json"], check=False)
    vj = json.loads(v.stdout[v.stdout.find("{"):])
    docs = vj["documents"]
    failing = {i["path"] for i in vj["issues"] if i["level"] == "error"}
    pass_rate = (docs - len(failing)) / docs if docs else 0.0
    per_validator = Counter(i["validator"] for i in vj["issues"] if i["level"] == "error")
    # Per-section records: contexts, references, flags.
    records = [json.load(open(f, encoding="utf-8")) for f in sorted(glob.glob(str(run_dir / ".ingest" / "*.json")))]
    ctx_words = [len(rec["context"].split()) for rec in records]
    xrefs = sum(len(rec["xrefs"]) for rec in records)
    low = sum(1 for rec in records for x in rec["xrefs"] if x["confidence"] < 0.8)
    flagged = sum(1 for rec in records if rec["flags"])
    doc_tokens = usage["document_tokens"]
    md = ["# Milestone H1: ingest agent v1\n"]
    md.append(f"Generated by `python eval/eval_h1.py --title {a.title}{' --limit ' + str(a.limit) if a.limit else ''}{' --dry-run' if a.dry_run else ''}` on {platform.system()} {platform.release()}; harness `@sectgrep/harness` on `@mariozechner/pi-agent-core` 0.73.1; model {'none (dry run)' if a.dry_run else 'from .env (OpenRouter, docs/decisions.md #41)'}.\n")
    md.append("## Run\n")
    md.append("| Run | Source | Sections | Staged | Failed | Fix rounds | Submitted | Wall s |")
    md.append("|---|---|---|---|---|---|---|---|")
    md.append(f"| {res['runId']}{' (reused)' if res.get('reused') else ''} | {source} | {res['sections']} | {res['staged']} | {len(res['failed'])} | {res['fixRounds']} | {'yes' if summary else 'no (' + str(res['errors']) + ' errors)'} | {secs:.0f} |")
    md.append("")
    md.append("## Validators on the staging\n")
    md.append(f"`sect-convert validate {run_dir.relative_to(ROOT) if run_dir.is_relative_to(ROOT) else run_dir} --corpus corpora/ecfr`: {docs} documents, {vj['errors']} errors, {vj['warnings']} warnings. **Pass rate {pass_rate:.3f}** ({docs - len(failing)} of {docs} documents with no error).\n")
    md.append("| # | Validator | Documents | Errors | Warnings |")
    md.append("|---|---|---|---|---|")
    for s in vj["validators"]:
        md.append(f"| {s['n']} | {s['name']} | {s['checked'] if not s.get('skipped') else 'skipped: ' + s['skipped']} | {s['errors']} | {s['warnings']} |")
    md.append("")
    for i in [i for i in vj["issues"] if i["level"] == "error"][:20]:
        md.append(f"- error [{i['validator']}] {i['path']}: {i['message']}")
    md.append("")
    md.append("## Cost\n")
    md.append("| Model calls | Prompt tokens | Completion tokens | Cost $ | Document tokens | Cost per document token $ | Cost per 1M document tokens $ |")
    md.append("|---|---|---|---|---|---|---|")
    per = usage["cost"] / doc_tokens if doc_tokens else 0.0
    md.append(f"| {usage['calls']} | {usage['input']} | {usage['output']} | {usage['cost']:.4f} | {doc_tokens} | {per:.8f} | {per * 1e6:.2f} |")
    md.append("")
    md.append("Document tokens are the word tokens of the sections' bodies; the spec's budget for the context prefix is on the order of $1 per million document tokens (D.2 step 4).\n")
    md.append("## What the agent produced\n")
    md.append(f"- {len(records)} sections staged; context prefixes of {min(ctx_words) if ctx_words else 0}-{max(ctx_words) if ctx_words else 0} words (mean {sum(ctx_words) / len(ctx_words) if ctx_words else 0:.0f}).")
    md.append(f"- {xrefs} references resolved as links, {low} below confidence 0.8 (listed in submit.json).")
    md.append(f"- {flagged} sections carry flags for a human.")
    if summary:
        md.append(f"- submit.json: {summary['sections_added']} added, {summary['xrefs_resolved']} references, {len(summary['low_confidence'])} low-confidence, {len(summary['flags'])} flags, {summary['warnings']} validator warnings.")
    if res["failed"]:
        md.append(f"- Not staged: {', '.join(f['input'] for f in res['failed'][:10])}.")
    md.append("")
    flags = Counter()
    for rec in records:
        for f in rec["flags"]:
            flags[f[:80]] += 1
    if flags:
        md.append("| Count | Flag (first 80 chars) |")
        md.append("|---|---|")
        for f, c in flags.most_common(12):
            md.append(f"| {c} | {f.replace('|', '/')} |")
        md.append("")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(md) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}: run {res['runId']}, pass rate {pass_rate:.3f}, cost ${usage['cost']:.4f} over {doc_tokens} document tokens (${per * 1e6:.2f}/M)")


if __name__ == "__main__":
    main()
